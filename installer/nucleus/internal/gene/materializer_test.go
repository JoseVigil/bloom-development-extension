func TestMaterializerUsesManagedGeneTelemetryStream(t *testing.T) {
	root := t.TempDir()
	logs := filepath.Join(root, "logs")
	logger, err := core.InitLogger(&core.Paths{LogsDir: logs, TelemetryDir: logs}, "GENE", true)
	if err != nil {
		t.Fatal(err)
	}
	s := &Store{Root: filepath.Join(root, "store"), Logger: logger}
	req := fixtureRequest(t, root)
	receipt, err := s.Materialize(req)
	if err != nil {
		_ = logger.Close()
		t.Fatal(err)
	}
	if _, err = s.Materialize(req); err != nil {
		_ = logger.Close()
		t.Fatal(err)
	}
	if err = logger.Close(); err != nil {
		t.Fatal(err)
	}

	telemetry, err := os.ReadFile(filepath.Join(logs, "telemetry.json"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(telemetry), `"nucleus_gene"`) {
		t.Fatalf("gene stream not registered: %s", telemetry)
	}
	if strings.Contains(string(telemetry), "GENE_CANONICAL_HEAD_PUBLISHED") {
		t.Fatal("event payload written directly to telemetry.json")
	}
	logFiles, err := filepath.Glob(filepath.Join(logs, "nucleus", "nucleus_gene_*.log"))
	if err != nil || len(logFiles) != 1 {
		t.Fatalf("logs=%v err=%v", logFiles, err)
	}
	logData, err := os.ReadFile(logFiles[0])
	if err != nil {
		t.Fatal(err)
	}
	for _, event := range []string{"GENE_MATERIALIZATION_STARTED", "GENE_CANONICAL_OBJECTS_INSTALLED", "GENE_CANONICAL_HEAD_PUBLISHED", "GENE_MATERIALIZATION_REPLAYED"} {
		if !strings.Contains(string(logData), event) {
			t.Fatalf("event %s missing from %s", event, logData)
		}
	}
	if !strings.Contains(string(logData), receipt.CanonicalCommitDigest) {
		t.Fatal("commit correlation missing from gene log")
	}
}
